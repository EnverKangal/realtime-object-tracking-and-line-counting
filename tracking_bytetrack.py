import cv2
import numpy as np
from ultralytics import YOLO
import supervision as sv

model = YOLO('yolov8n.pt')
video_path = "car_test.mp4"
video_info = sv.VideoInfo.from_video_path(video_path)

# Dikey çizgimiz (x ekseninde ekranın ortası)
line_x = int(video_info.width * 0.5)

box_annotator = sv.BoxAnnotator(thickness=2)
label_annotator = sv.LabelAnnotator(text_scale=0.5, text_thickness=1)
byte_tracker = sv.ByteTrack()

# Takip mantığı için hafıza:
# Her ID'nin önceki x koordinatını ve sayılan ID'leri tutuyoruz
previous_x_positions = {}
counted_ids = set()
in_count = 0
out_count = 0

TARGET_CLASSES = [2, 3, 5, 7, 6]  # car, motorcycle, bus, truck, train

def process_frame(frame: np.ndarray, index: int) -> np.ndarray:
    global in_count, out_count

    results = model(frame, verbose=False, conf=0.2)[0]
    detections = sv.Detections.from_ultralytics(results)
    detections = detections[np.isin(detections.class_id, TARGET_CLASSES)]
    detections = byte_tracker.update_with_detections(detections)

    labels = []
    if len(detections) > 0 and detections.tracker_id is not None:
        for xyxy, tracker_id, class_id in zip(detections.xyxy, detections.tracker_id, detections.class_id):
            labels.append(f"#{tracker_id} {model.names[class_id]}")

            # Kutunun merkez x noktası
            center_x = (xyxy[0] + xyxy[2]) / 2

            # Önceki koordinat varsa çizgi geçiş kontrolü yap
            if tracker_id in previous_x_positions:
                prev_x = previous_x_positions[tracker_id]

                if tracker_id not in counted_ids:
                    # Soldan sağa geçiş
                    if prev_x < line_x and center_x >= line_x:
                        in_count += 1
                        counted_ids.add(tracker_id)
                    # Sağdan sola geçiş
                    elif prev_x > line_x and center_x <= line_x:
                        out_count += 1
                        counted_ids.add(tracker_id)

            previous_x_positions[tracker_id] = center_x

    annotated = box_annotator.annotate(scene=frame.copy(), detections=detections)
    if labels:
        annotated = label_annotator.annotate(scene=annotated, detections=detections, labels=labels)

    # Çizgiyi ve sayacı görsel olarak ekrana çiziyoruz
    cv2.line(annotated, (line_x, 0), (line_x, video_info.height), (0, 0, 255), 2)
    cv2.putText(annotated, f"In: {in_count} | Out: {out_count}", (30, 50),
                cv2.FONT_HERSHEY_SIMPLEX, 1, (0, 255, 0), 2)

    return annotated

print("Kendi çizgi takip algoritmamızla video işleniyor...")
