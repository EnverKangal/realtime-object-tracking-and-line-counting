    # Nesne takibi (ByteTrack)
    detections = byte_tracker.update_with_detections(detections)

    # Çizgiden geçenleri tetikle
    line_zone.trigger(detections=detections)

    # Ekrana çizimler (Güncel Supervision parametreleri)
