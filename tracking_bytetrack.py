# 100 karelik, 640x480 boyutunda sentetik bir otoyol videosu oluşturalım
width, height = 640, 480
fps = 20
fourcc = cv2.VideoWriter_fourcc(*'mp4v')
out = cv2.VideoWriter('traffic_sim.mp4', fourcc, fps, (width, height))

# 3 farklı aracın yukarıdan aşağıya doğru hareketini çizelim
for frame_idx in range(100):
    frame = np.full((height, width, 3), 40, dtype=np.uint8)  # Asfalt zemin

    # Şerit çizgileri
    cv2.line(frame, (width // 2, 0), (width // 2, height), (255, 255, 255), 2)

    # 1. Araç (Sol şerit)
    y1 = int(frame_idx * 5)
    if y1 < height:
        cv2.rectangle(frame, (200, y1), (280, y1 + 100), (0, 0, 255), -1)  # Kırmızı araç

    # 2. Araç (Sağ şerit, biraz geriden gelen)
    y2 = int((frame_idx - 25) * 6)
    if 0 <= y2 < height:
        cv2.rectangle(frame, (360, y2), (440, y2 + 110), (255, 100, 0), -1)  # Mavi araç

    out.write(frame)

out.release()
